#!/usr/bin/env python3
"""Zephyr Anel: shared vector geometry. Run from any directory.
Raster exports require Pillow and system librsvg/gdk-pixbuf; SVG/Android need stdlib only.
"""
from pathlib import Path
import math, sys
ROOT=Path(__file__).resolve().parents[1]
GREEN='#86D92F'; DARK='#04150F'; SILVER='#E6E9E2'
Z='M82 76 H182 Q191 76 186 84 L113 157 H178 L168 174 Q166 178 160 178 H73 Q65 178 70 170 L144 97 H72 Z'
def arcs():
    result=[]
    for a in (8,98,188,278):
        def pt(deg):
            t=math.radians(deg); return (128+102*math.cos(t),128+102*math.sin(t))
        x,y=pt(a); u,v=pt(a+74)
        result.append(f'M{x:.4f} {y:.4f} A102 102 0 0 1 {u:.4f} {v:.4f}')
    return result
ARCS=arcs()
def mark(flat=False,mono=False):
    color=SILVER if mono else GREEN
    return ''.join(f'<path d="{p}" fill="none" stroke="{color}" stroke-width="17" stroke-linecap="round"/>' for p in ARCS)+f'<path d="{Z}" fill="{SILVER if flat or mono else "url(#silver)"}"/>'
DEFS='<defs><linearGradient id="silver" x1="0" y1="0" x2=".8" y2="1"><stop stop-color="#FAFCF5"/><stop offset=".45" stop-color="#CAD1C8"/><stop offset=".65" stop-color="#F4F6EF"/><stop offset="1" stop-color="#9DAA9F"/></linearGradient></defs>'
def svg(body,w=256,h=256,title='Zephyr-Mobile — Anel'):
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img"><title>{title}</title>{DEFS}{body}</svg>\n'
def write(path,text):
    p=ROOT/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text)
def vector(scale=1,translate=0,back=False,mono=False):
    paths=''.join(f'<path android:pathData="{p}" android:fillColor="#00000000" android:strokeColor="{SILVER if mono else GREEN}" android:strokeWidth="17" android:strokeLineCap="round"/>' for p in ARCS)
    paths+=f'<path android:pathData="{Z}" android:fillColor="{SILVER}"/>'
    bg=f'<path android:fillColor="{DARK}" android:pathData="M0 0H256V256H0Z"/>' if back else ''
    vp=108 if scale!=1 else 256
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/generate.py: Anel. Do not hand-edit geometry. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{vp}dp" android:height="{vp}dp" android:viewportWidth="{vp}" android:viewportHeight="{vp}">{bg}<group android:scaleX="{scale}" android:scaleY="{scale}" android:translateX="{translate}" android:translateY="{translate}">{paths}</group></vector>
'''
write('docs/assets/zephyr-mark.svg',svg(mark()))
write('docs/assets/zephyr-mark-flat.svg',svg(mark(flat=True)))
write('docs/assets/zephyr-icon.svg',svg(f'<rect width="256" height="256" rx="52" fill="{DARK}"/>'+f'<g transform="translate(24 24) scale(.8125)">{mark()}</g>'))
for mode,fg,bg in [('dark',SILVER,DARK),('light',DARK,'#F4F5EF')]:
    body=f'<rect width="1000" height="300" rx="24" fill="{bg}"/><g transform="translate(35 22) scale(1)">{mark()}</g><g fill="{fg}" font-family="Arial,Helvetica,sans-serif"><text x="325" y="157" font-size="86" font-style="italic" font-weight="700" letter-spacing="3">ZEPHYR</text><text x="333" y="211" font-size="28" letter-spacing="20" fill="{GREEN if mode=="dark" else "#387600"}">MOBILE</text></g>'
    write(f'docs/assets/zephyr-logo-on-{mode}.svg',svg(body,1000,300))
body=f'<rect width="1280" height="420" rx="24" fill="{DARK}"/><rect x="24" y="24" width="1232" height="372" rx="20" fill="none" stroke="#264F32"/><g transform="translate(64 52) scale(1.23)">{mark()}</g><g font-family="Arial,Helvetica,sans-serif"><text x="440" y="109" fill="{GREEN}" font-size="14" letter-spacing="5">ANEL · ZEPHYR RESEARCH</text><text x="430" y="218" fill="{SILVER}" font-size="91" font-style="italic" font-weight="700" letter-spacing="1">ZEPHYR</text><text x="440" y="274" fill="{GREEN}" font-size="33" letter-spacing="19">MOBILE</text><path d="M440 304H1180" stroke="#264F32"/><text x="440" y="341" fill="#B8D4C8" font-size="18">Xbox 360 emulation · Android · ARM64 · Vulkan</text><text x="440" y="372" fill="#86A394" font-size="14">Motorola Edge 30 Ultra · A Pixel Code project</text></g>'
write('docs/assets/zephyr-mobile-banner.svg',svg(body,1280,420))
write('app/src/main/res/drawable/zephyr_brand_mark.xml',vector())
write('app/src/main/res/drawable/zephyr_app_icon.xml',vector(back=True))
# 60.8-unit mark inside Android's central 66-unit safe circle, including strokes.
write('app/src/main/res/drawable/zephyr_launcher_foreground.xml',vector(.275,18.8))
write('app/src/main/res/drawable/zephyr_launcher_monochrome.xml',vector(.275,18.8,mono=True))
write('app/src/main/res/drawable/zephyr_launcher_background.xml',f'<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle"><solid android:color="{DARK}"/></shape>\n')
# System splash: use filled backing and ring on Android 12+; no runtime animation/timers.
write('app/src/main/res/values-v31/themes.xml',f'''<resources><style name="Theme.xendroidCompose" parent="android:Theme.Material.Light.NoActionBar"><item name="android:windowSplashScreenBackground">{DARK}</item><item name="android:windowSplashScreenAnimatedIcon">@drawable/zephyr_launcher_foreground</item><item name="android:windowLightStatusBar">false</item><item name="android:statusBarColor">{DARK}</item></style></resources>\n''')
if '--vectors-only' in sys.argv: sys.exit(0)
# Rasterize authored vectors. No AI image manipulation: these are native asset exports.
import ctypes
from PIL import Image
r=ctypes.CDLL('librsvg-2.so.2');g=ctypes.CDLL('libgdk_pixbuf-2.0.so.0');obj=ctypes.CDLL('libgobject-2.0.so.0')
r.rsvg_handle_new_from_data.argtypes=[ctypes.c_char_p,ctypes.c_size_t,ctypes.c_void_p];r.rsvg_handle_new_from_data.restype=ctypes.c_void_p
r.rsvg_handle_get_pixbuf.argtypes=[ctypes.c_void_p];r.rsvg_handle_get_pixbuf.restype=ctypes.c_void_p
g.gdk_pixbuf_savev.argtypes=[ctypes.c_void_p,ctypes.c_char_p,ctypes.c_char_p,ctypes.c_void_p,ctypes.c_void_p,ctypes.c_void_p];g.gdk_pixbuf_savev.restype=ctypes.c_int
obj.g_object_unref.argtypes=[ctypes.c_void_p]
def render(text):
    data=text.encode();handle=r.rsvg_handle_new_from_data(data,len(data),None); pix=r.rsvg_handle_get_pixbuf(handle)
    temp=ROOT/'branding/.render.png'
    if not g.gdk_pixbuf_savev(pix,str(temp).encode(),b'png',None,None,None): raise RuntimeError('SVG export failed')
    im=Image.open(temp).convert('RGBA');im.load();temp.unlink();obj.g_object_unref(pix);obj.g_object_unref(handle);return im
base=render(svg(mark())); icon=render((ROOT/'docs/assets/zephyr-icon.svg').read_text())
out=ROOT/'website/src/assets/brand';out.mkdir(parents=True,exist_ok=True)
def save(im,path):
    im.save(path,**({'quality':95,'method':6} if str(path).endswith('.webp') else {}))
for px in (64,128,256):
    im=base.resize((px,px),Image.Resampling.LANCZOS)
    for ext in ('png','webp'):save(im,out/f'mark-{px}.{ext}')
for px,name in [(32,'favicon-32.png'),(180,'apple-touch-icon.png'),(192,'icon-192.png'),(512,'icon-512.png')]:save(icon.resize((px,px),Image.Resampling.LANCZOS),out/name)
icon.save(out/'favicon.ico',sizes=[(16,16),(32,32),(48,48)])
for mode in ('dark','light'):
    im=render((ROOT/f'docs/assets/zephyr-logo-on-{mode}.svg').read_text())
    for w,suffix in [(440,''),(880,'@2x')]:save(im.resize((w,round(w*.3)),Image.Resampling.LANCZOS),out/f'logo-on-{mode}{suffix}.webp')
banner=render((ROOT/'docs/assets/zephyr-mobile-banner.svg').read_text());save(banner,ROOT/'branding/preview.png')
og=Image.new('RGBA',(1200,630),DARK);b=banner.resize((1200,394),Image.Resampling.LANCZOS);og.alpha_composite(b,(0,118));og.convert('RGB').save(out/'og-image.png')
for density,px in [('mdpi',48),('hdpi',72),('xhdpi',96),('xxhdpi',144),('xxxhdpi',192)]:
    folder=ROOT/f'app/src/main/res/mipmap-{density}';folder.mkdir(parents=True,exist_ok=True)
    for name in ('ic_launcher','ic_launcher_round'):save(icon.resize((px,px),Image.Resampling.LANCZOS),folder/f'{name}.webp')
    # No raster fallback may retain the old mark.
    fg=Image.new('RGBA',(int(px*2.25),int(px*2.25)),(0,0,0,0));m=base.resize((round(fg.width*.565),)*2,Image.Resampling.LANCZOS);fg.alpha_composite(m,((fg.width-m.width)//2,)*2)
    save(fg,folder/'ic_launcher_foreground.webp');save(Image.new('RGB',fg.size,DARK),folder/'ic_launcher_background.webp')
save(base,ROOT/'app/src/main/res/drawable-nodpi/xd_logo_mark.webp')
# Compatibility filenames for existing references now export the Zephyr logo, not old artwork.
for mode,name in [('light','xendroid-plus-logo.png'),('dark','xendroid-plus-logo-dark.png')]:save(render((ROOT/f'docs/assets/zephyr-logo-on-{mode}.svg').read_text()),ROOT/'docs/assets'/name)
print('Anel assets generated: Android, SVG, web icons, favicon, Open Graph and repository banner')
